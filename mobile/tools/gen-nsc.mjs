// Writes android/app/src/main/res/xml/network_security_config.xml.
// Cleartext (http) is allowed only for localhost, the emulator host, and the http:// hosts
// listed in VITE_AI_SERVERS (read from ../client/.env.local, never modified).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const envFile = join(here, '..', '..', 'client', '.env.local');
const out = join(here, '..', 'android', 'app', 'src', 'main', 'res', 'xml', 'network_security_config.xml');

const hosts = new Set(['localhost', '127.0.0.1', '10.0.2.2']);
if (existsSync(envFile)) {
  const line = readFileSync(envFile, 'utf8').split(/\r?\n/).find((l) => /^\s*VITE_AI_SERVERS\s*=/.test(l));
  if (line) {
    const raw = line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '');
    for (const s of raw.split(/[,\s]+/).filter(Boolean)) {
      try {
        const u = new URL(s);
        if (u.protocol === 'http:' && /^[A-Za-z0-9.\-]+$/.test(u.hostname)) hosts.add(u.hostname);
      } catch { /* ignore malformed entries */ }
    }
  }
}

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-nsc.mjs. Cleartext is denied by default; allowed hosts come from VITE_AI_SERVERS. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${[...hosts].map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;
writeFileSync(out, xml);
console.log('network_security_config: cleartext allowed for ' + [...hosts].join(', '));
